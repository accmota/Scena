def normalize_preset_name(name: str) -> str:
    """Lowercase and collapse spaces/hyphens to underscores."""
    return str(name or "").strip().lower().replace("-", "_").replace(" ", "_")


def preset_names() -> Tuple[str, ...]:
    """Sorted preset keys."""
    return tuple(sorted(GRADIENT_PRESETS.keys()))


def get_preset(name: str) -> Optional[List[Stop]]:
    """Return stop list for ``name``, or None if unknown."""
    key = normalize_preset_name(name)
    stops = GRADIENT_PRESETS.get(key)
    if stops is None:
        return None
    return list(stops)


def sample_stops_rgb(
    stops: Sequence[Stop],
) -> Tuple[RGB, RGB, RGB]:
    """Return first, middle, and last stop colours (for sky top/middle/bottom)."""
    if not stops:
        raise ValueError("stops must be non-empty")
    first = stops[0][1]
    last = stops[-1][1]
    mid_i = len(stops) // 2
    mid = stops[mid_i][1]
    return first, mid, last
